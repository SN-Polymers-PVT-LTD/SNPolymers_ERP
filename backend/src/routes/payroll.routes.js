const router = require('express').Router();
const verifyJwt = require('../middleware/verifyJwt');
const requireRole = require('../middleware/requireRole');
const requireCurrentHrRole = require('../middleware/requireCurrentHrRole');
const validateRequest = require('../middleware/validateRequest');
const schema = require('../validation/payroll.schema');
const controller = require('../controllers/payroll.controller');
router.use(verifyJwt, requireCurrentHrRole(['admin', 'accounts', 'ho', 'factory_manager']));
const masterSchema = require('../validation/payrollMasters.schema');
const masters = require('../controllers/payrollMasters.controller');
router.get('/masters/:kind', requireRole(['admin']), validateRequest(masterSchema.list), masters.list);
router.post('/masters/:kind/drafts', requireRole(['admin']), validateRequest(masterSchema.save), masters.save);
router.get('/masters/:kind/resolve', requireRole(['admin']), validateRequest(masterSchema.resolve), masters.resolve);
router.get('/masters/:kind/:id/preview', requireRole(['admin']), validateRequest(masterSchema.preview), masters.preview);
router.post('/masters/:kind/:id/publish', requireRole(['admin']), validateRequest(masterSchema.publish), masters.publish);
const reports = require('../controllers/payrollReports.controller');
const reportSchema = require('../validation/payrollReports.schema');
router.get('/reports/register', validateRequest(reportSchema.register), reports.register);
router.get('/reports/export', validateRequest(reportSchema.export), reports.exportReport);
router.get('/rows/:rowId/payslip', validateRequest(reportSchema.payslip), reports.payslip);
const previews = require('../controllers/payrollPreview.controller');
const review = require('../controllers/payrollReview.controller');
const reviewSchema = require('../validation/payrollReview.schema');
router.get('/review/queue', validateRequest(reviewSchema.queue), review.queue);
router.post('/review/bulk', validateRequest(reviewSchema.bulk), review.bulk);
router.get('/rows/:rowId/review', validateRequest(reviewSchema.detail), review.detail);
router.post('/rows/:rowId/review', validateRequest(reviewSchema.action), review.act);
router.get('/runs', validateRequest(schema.listRuns), previews.list);
router.post('/rows/:rowId/preview', validateRequest(schema.preview), previews.preview);
router.get('/context', controller.context);
router.post('/factory-scopes', requireRole(['admin']), validateRequest(schema.scope), controller.setScope);
router.post('/source-history', requireRole(['admin']), validateRequest(schema.history), controller.recordHistory);
router.get('/employees/:employeeId/source-history', requireRole(['admin']), validateRequest(schema.employeeHistory), controller.sourceHistory);
router.post('/runs', requireRole(['admin', 'accounts', 'factory_manager']), validateRequest(schema.createRun), controller.createRun);
router.get('/runs/:runId/candidates', validateRequest(schema.detail), controller.candidates);
router.get('/runs/:runId', validateRequest(schema.detail), controller.detail);
router.post('/runs/:runId/employees', requireRole(['admin', 'accounts', 'factory_manager']), validateRequest(schema.addEmployee), controller.addEmployee);
router.patch('/rows/:rowId/note', requireRole(['admin', 'accounts', 'factory_manager']), validateRequest(schema.reviseNote), controller.reviseNote);
module.exports = router;
